function addDays(iso, n) {
  const d = new Date(`${iso}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

function fm(obj) {
  const lines = ["---"];
  for (const [k, v] of Object.entries(obj)) {
    if (v === null) lines.push(`${k}: null`);
    else if (Array.isArray(v)) {
      if (v.length === 0) lines.push(`${k}: []`);
      else if (typeof v[0] === "string") {
        lines.push(`${k}:`);
        for (const item of v) lines.push(`  - ${JSON.stringify(item)}`);
      } else {
        lines.push(`${k}:`);
        for (const item of v) {
          lines.push("  -");
          for (const [ik, iv] of Object.entries(item)) {
            lines.push(`    ${ik}: ${JSON.stringify(iv)}`);
          }
        }
      }
    } else if (typeof v === "string") lines.push(`${k}: ${JSON.stringify(v)}`);
    else lines.push(`${k}: ${JSON.stringify(v)}`);
  }
  lines.push("---", "");
  return lines.join("\n");
}

function write(rel, front, body) {
  const full = path.join(OUT, rel);
  if (rel === "el-shorouk/prices-2026.md" && fs.existsSync(full)) {
    console.log("skip existing", rel);
    return;
  }
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, fm(front) + body.trim() + "\n", "utf8");
  console.log("wrote", rel);
}

