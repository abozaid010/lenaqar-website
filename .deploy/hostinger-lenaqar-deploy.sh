#!/usr/bin/env bash
# Runs ON the Hostinger VPS (piped over SSH by .github/workflows/deploy-hostinger.yml,
# or by hand). Blue/green roll for lenaqar.com:
#   1. build lenaqar-web:<TAG> from /opt/lenaai/src/lenaqar
#   2. start the INACTIVE color (blue=127.0.0.1:3010, green=127.0.0.1:3011)
#   3. health-check /api/version (must report GIT_SHA), switch the nginx upstream,
#      verify through nginx, stop the old color, keep the last 3 images
# It never touches the lenaai containers, their active_color or switch-traffic.sh.
# If any check fails before the switch, the live color is untouched.
set -Eeuo pipefail

ROOT=/opt/lenaai
SRC="$ROOT/src/lenaqar"
TAG="${TAG:?TAG is required, e.g. TAG=202611281200-abc1234}"
GIT_SHA="${GIT_SHA:?GIT_SHA is required (full or short commit sha)}"
ENV_FILE="$ROOT/secrets/lenaqar.env"
COMPOSE="$ROOT/compose/docker-compose.lenaqar.yml"
STATE="$ROOT/lenaqar_active_color"
UPSTREAM=/etc/nginx/conf.d/lenaqar_upstream.conf
SITE=/etc/nginx/sites-enabled/lenaqar
CERT=/etc/letsencrypt/live/lenaqar.com/fullchain.pem
KEEP="${KEEP:-3}"

port_of() { case "$1" in blue) echo 3010 ;; green) echo 3011 ;; *) return 1 ;; esac; }
other_color() { case "$1" in blue) echo green ;; *) echo blue ;; esac; }
compose() { # compose <color> <image> <args...>
  local c="$1" img="$2"; shift 2
  LENAQAR_COLOR="$c" LENAQAR_HOST_PORT="$(port_of "$c")" LENAQAR_IMAGE="$img" \
    docker compose -p "lenaqar-$c" -f "$COMPOSE" "$@"
}

# Same lock as the lenaai deploys: one docker build at a time on this 2-vCPU box.
exec 9>"$ROOT/.deploy.lock"
if ! flock -w 900 9; then
  echo "Another deploy holds $ROOT/.deploy.lock"
  exit 1
fi

[ -f "$ENV_FILE" ] || { echo "Missing $ENV_FILE" >&2; exit 1; }
[ -d "$SRC" ] || { echo "Missing source $SRC" >&2; exit 1; }
install -m 644 "$SRC/.deploy/docker-compose.lenaqar.yml" "$COMPOSE"

ACTIVE="$(tr -d '[:space:]' <"$STATE" 2>/dev/null || true)"
case "$ACTIVE" in blue|green) ;; *) ACTIVE="" ;; esac
INACTIVE="$(other_color "${ACTIVE:-green}")"
PORT="$(port_of "$INACTIVE")"
IMAGE="lenaqar-web:$TAG"
echo "Active=${ACTIVE:-none}  ->  deploying $IMAGE to $INACTIVE (:$PORT)"

# ---- 1. build (env file is a BuildKit secret: never stored in a layer) ----
echo "==> docker build $IMAGE"
DOCKER_BUILDKIT=1 docker build \
  --secret id=env,src="$ENV_FILE" \
  --build-arg GIT_SHA="$GIT_SHA" \
  --build-arg BUILT_AT="$(date -u +%FT%TZ)" \
  -t "$IMAGE" "$SRC"

# ---- 2. start inactive color ----
echo "==> start lenaqar-web-$INACTIVE"
compose "$INACTIVE" "$IMAGE" up -d --force-recreate --remove-orphans

# ---- 3. health-check: right build answering, home page renders ----
ok=0
for _ in $(seq 1 30); do
  if curl -fsS --max-time 5 "http://127.0.0.1:$PORT/api/version" | grep -q "\"sha\":\"$GIT_SHA\"" \
    && curl -fsS -o /dev/null --max-time 30 "http://127.0.0.1:$PORT/"; then
    ok=1; break
  fi
  sleep 5
done
if [ "$ok" != 1 ]; then
  echo "Health check FAILED - traffic NOT switched. ${ACTIVE:-nothing} is still live."
  docker logs --tail 80 "lenaqar-web-$INACTIVE" || true
  exit 1
fi
echo "health OK on :$PORT"

# ---- 4. switch nginx upstream ----
write_upstream() {
  local tmp; tmp="$(mktemp)"
  printf '# Generated by hostinger-lenaqar-deploy.sh - active color: %s\nupstream lenaqar_upstream {\n    server 127.0.0.1:%s;\n    keepalive 16;\n}\n' "$1" "$(port_of "$1")" >"$tmp"
  install -m 644 "$tmp" "$UPSTREAM"; rm -f "$tmp"
}
nginx_workers() { ps -C nginx -o pid=,cmd= | awk '/worker process/ {print $1}' | sort | tr '\n' ' '; }
reload_nginx() {
  local before; before="$(nginx_workers)"
  nginx -t -q || return 1
  systemctl reload nginx || return 1
  sleep 1
  if [ "$before" = "$(nginx_workers)" ]; then
    echo "nginx reload kept the previous workers; restarting nginx"
    systemctl restart nginx; sleep 1
  fi
}
prev_upstream="$(cat "$UPSTREAM" 2>/dev/null || true)"
echo "==> switch nginx -> $INACTIVE"
write_upstream "$INACTIVE"
if ! reload_nginx; then
  echo "nginx rejected the new upstream - restoring the previous file"
  if [ -n "$prev_upstream" ]; then printf '%s\n' "$prev_upstream" >"$UPSTREAM"; else rm -f "$UPSTREAM"; fi
  nginx -t -q && systemctl reload nginx
  exit 1
fi

# Through nginx, only once the lenaqar site is enabled (first deploy runs before it).
if [ -e "$SITE" ]; then
  sleep 2
  if [ -f "$CERT" ]; then
    check=(curl -fsS -o /dev/null --max-time 30 --resolve www.lenaqar.com:443:127.0.0.1 https://www.lenaqar.com/)
  else
    check=(curl -fsS -o /dev/null --max-time 30 -H 'Host: www.lenaqar.com' http://127.0.0.1/)
  fi
  if ! "${check[@]}"; then
    echo "Post-switch check FAILED"
    if [ -n "$ACTIVE" ]; then
      echo "rolling back to $ACTIVE"; write_upstream "$ACTIVE"; reload_nginx
    fi
    exit 1
  fi
  echo "post-switch check OK through nginx"
fi
echo "$INACTIVE" >"$STATE"

# ---- 5. stop old color (rollback: start it again + rerun with the old TAG, or
#      write the old port into $UPSTREAM and reload nginx) ----
if [ -n "$ACTIVE" ]; then
  echo "==> stop old color $ACTIVE"
  compose "$ACTIVE" "unused" stop || true
fi

# ---- 6. keep the newest $KEEP lenaqar-web builds plus any image a container uses ----
in_use="$(docker ps -a --format '{{.Image}}' | sort -u)"
docker images lenaqar-web --format '{{.Repository}}:{{.Tag}}' \
  | { grep -vE ':(local|latest|<none>)$' || true; } \
  | tail -n +"$((KEEP + 1))" \
  | while read -r img; do
      grep -qxF "$img" <<<"$in_use" || { echo "remove $img"; docker rmi "$img" >/dev/null || true; }
    done
docker image prune -f >/dev/null || true
echo "DEPLOYED $IMAGE on $INACTIVE (sha $GIT_SHA)"
